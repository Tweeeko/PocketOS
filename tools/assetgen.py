"""Generate PocketOS UI assets as LVGL 9 C sources (no LVGL tools needed).

  - Inter fonts (SIL Open Font License) at the sizes the UI uses, 4 bpp, LVGL fmt_txt format
  - Icons drawn from the same SVG paths as the browser prototype, as A8 (alpha) images
  - The 466x466 background with soft blue/violet glows, RGB565

Usage: python3 tools/assetgen.py [--inter-dir /usr/share/fonts/opentype/inter]
Icons are rendered with Playwright/Chromium. Output: firmware/main/ui/assets/
"""
