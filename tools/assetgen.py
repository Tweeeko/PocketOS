def gen_icons():
    from playwright.sync_api import sync_playwright
    decls, srcs = [], [HEADER]
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page(device_scale_factor=1)
        for size, names in SIZES.items():
            for nm in names:
                d = ICONS[nm]
                fill = d.startswith('!')
                d = d.lstrip('!')
                sw = 1.8 if size < 60 else 1.5
                svg = ('<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 24 24" fill="%s" stroke="#fff" '
                       'stroke-width="%s" stroke-linecap="round" stroke-linejoin="round"><path d="%s"/></svg>') % (
                    size, size, '#fff' if fill else 'none', '0' if fill else sw, d)
                pg.set_content('<html><body style="margin:0;background:transparent">%s</body></html>' % svg)
                pg.set_viewport_size({'width': size, 'height': size})
                png = pg.screenshot(omit_background=True, clip={'x': 0, 'y': 0, 'width': size, 'height': size})
                from io import BytesIO
                a = np.array(Image.open(BytesIO(png)).convert('RGBA'))[:, :, 3].astype(np.uint8)
                cname = 'ic_%s_%d' % (nm, size)
                srcs.append('static const uint8_t %s_map[] = {\n%s\n};\nconst lv_image_dsc_t %s = {\n'
                            '    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .flags = 0, .w = %d, .h = %d, .stride = %d},\n'
                            '    .data_size = sizeof(%s_map), .data = %s_map,\n};\n' % (cname, c_bytes(a.flatten().tolist()), cname, size, size, size, cname, cname))
                decls.append(cname)
        b.close()
    open(os.path.join(OUT, 'icons.c'), 'w').write('\n'.join(srcs))
    return decls


def gen_background():
    W = H = 466
    y, x = np.mgrid[0:H, 0:W].astype(np.float32)

    def glow(cx, cy, r, color, k):
        d = np.sqrt((x - cx) ** 2 + (y - cy) ** 2) / r
        a = np.clip(1 - d, 0, 1) ** 2 * k
        return a[..., None] * np.array(color, np.float32)[None, None, :]

    img = np.zeros((H, W, 3), np.float32)
    img += glow(140, 120, 300, (106, 167, 255), 0.30)
    img += glow(335, 330, 300, (155, 123, 255), 0.30)
    img += glow(330, 110, 200, (80, 220, 200), 0.10)
    img += np.random.default_rng(7).uniform(-1.2, 1.2, img.shape)  # dither to avoid banding in RGB565
    img = np.clip(img, 0, 255).astype(np.uint16)
    rgb565 = ((img[..., 0] >> 3) << 11) | ((img[..., 1] >> 2) << 5) | (img[..., 2] >> 3)
    data = rgb565.astype('<u2').tobytes()
    src = HEADER + 'static LV_ATTRIBUTE_LARGE_CONST const uint8_t bg_map[] = {\n%s\n};\nconst lv_image_dsc_t img_bg = {\n' \
        '    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565, .flags = 0, .w = %d, .h = %d, .stride = %d},\n' \
        '    .data_size = sizeof(bg_map), .data = bg_map,\n};\n' % (c_bytes(list(data), 32), W, H, W * 2)
    open(os.path.join(OUT, 'bg.c'), 'w').write(src)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--inter-dir', default='/usr/share/fonts/opentype/inter')
    args = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)
    fonts = [gen_font(n, os.path.join(args.inter_dir, f), s) for n, f, s in FONTS]
    icons = gen_icons()
    gen_background()
    h = ['/* Generated by tools/assetgen.py - do not edit. */', '#pragma once', '#include "lvgl.h"', '']
    h += ['extern const lv_font_t %s;' % f for f in fonts]
    h += ['extern const lv_image_dsc_t %s;' % i for i in icons]
    h += ['extern const lv_image_dsc_t img_bg;']
    open(os.path.join(OUT, 'assets.h'), 'w').write('\n'.join(h) + '\n')
    print('fonts:', len(fonts), 'icons:', len(icons))


if __name__ == '__main__':
    main()
