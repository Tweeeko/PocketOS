OUT = os.path.join(ROOT, 'firmware', 'main', 'ui', 'assets')

GLYPHS = [c for c in range(0x20, 0x7F)] + [0xB0, 0xB7, 0xD7, 0x2013, 0x2019, 0x201C, 0x201D, 0x2026]

# name, file, pixel size
