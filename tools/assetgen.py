HEADER = '''/* Generated by tools/assetgen.py - do not edit. */
#include "lvgl.h"
'''


def c_bytes(data, per_line=24):
    out = []
    for i in range(0, len(data), per_line):
        out.append('    ' + ','.join('0x%02x' % b for b in data[i:i + per_line]) + ',')
    return '\n'.join(out)


def gen_font(name, path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    bitmap = bytearray()
    dscs = ['    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id 0 reserved */']
    for cp in GLYPHS:
        ch = chr(cp)
        adv = int(round(font.getlength(ch) * 16))
        x0, y0, x1, y1 = font.getbbox(ch, anchor='ls')
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        idx = len(bitmap)
        if w and h:
            img = Image.new('L', (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor='ls')
            px = np.array(img, dtype=np.uint8) >> 4  # 4 bpp
            flat = px.flatten().tolist()
            if len(flat) % 2:
                flat.append(0)
            for i in range(0, len(flat), 2):
                bitmap.append((flat[i] << 4) | flat[i + 1])
        dscs.append('    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d} /* U+%04X */'
                    % (idx, adv, w, h, x0, -y1, cp))
    first = GLYPHS[0]
    offs = [cp - first for cp in GLYPHS]
    src = HEADER + '''
static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {
%s
};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {
%s
};

static const uint16_t unicode_list[] = {%s};

static const lv_font_fmt_txt_cmap_t cmaps[] = {
    {.range_start = %d, .range_length = %d, .glyph_id_start = 1, .unicode_list = unicode_list,
     .glyph_id_ofs_list = NULL, .list_length = %d, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}
};

static const lv_font_fmt_txt_dsc_t font_dsc = {
    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,
    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 1, .bpp = 4, .kern_classes = 0, .bitmap_format = 0, .stride = 0,
};

const lv_font_t %s = {
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = %d,
    .base_line = %d,
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -2,
    .underline_thickness = 1,
    .dsc = &font_dsc,
    .fallback = NULL,
};
''' % (c_bytes(bitmap), ',\n'.join(dscs), ','.join(map(str, offs)), first, GLYPHS[-1] - first + 1, len(GLYPHS),
       name, ascent + descent, descent)
    open(os.path.join(OUT, name + '.c'), 'w').write(src)
    return name


